with open('data/yichuan_clean.txt', 'r', encoding='utf-8') as f:
    text = f.read()

# 全面替换校勘 OCR 异体字与错字
text = text.replace('防上', '巽上').replace('防下', '巽下').replace('【防', '【巽').replace('防】', '巽】')
text = text.replace('干上', '乾上').replace('干下', '乾下').replace('【干', '【乾').replace('干】', '乾】')
text = text.replace('兊上', '兑上').replace('兊下', '兑下').replace('【兊', '【兑').replace('兊】', '兑】')
text = text.replace('頥', '颐').replace('遯', '遁').replace('暌', '睽')

pattern = r'([^\n]*【[乾坤震巽坎离艮兑]+下[乾坤震巽坎离艮兑]+上】)'
splits = list(re.finditer(pattern, text))
print(f"Total gua splits after full normalization: {len(splits)}")

blocks = {}
for i in range(len(splits)):
    start_pos = splits[i].start()
    end_pos = splits[i+1].start() if i < len(splits) - 1 else len(text)
    block_str = text[start_pos:end_pos].strip()
    gid = i + 1
    if gid <= 64:
        blocks[gid] = block_str

target_dir = "05_易学经典原典馆/02_伊川易传_程颐"
archive_dir = "02_六十四卦精研档案"
os.makedirs(target_dir, exist_ok=True)

# 生成 64 篇原典
for gid, full_name, short_name, structure, binary in GUA_DEFS:
    b_text = blocks.get(gid, "")
    
    # 格式化排版
    b_text = re.sub(r'([初九六][一二三四五九六])', r'\n\n### 爻位【\1】：', b_text)
    b_text = re.sub(r'(彖曰[：:]?)', r'\n\n### 《彖传》大义：\n', b_text)
    b_text = re.sub(r'(象曰[：:]?)', r'\n\n- **小象传**：', b_text)
    b_text = re.sub(r'(文言曰[：:]?)', r'\n\n### 《文言传》阐发：\n', b_text)
    b_text = re.sub(r'\n{3,}', '\n\n', b_text)
    
    doc = f"""---
title: 伊川易传 · {full_name}
author: 〔北宋〕程颐
book: 伊川易传（周易程氏传）
gua_id: {gid}
gua_name: {full_name}
edition: 文渊阁《四库全书》本校正
---

# 伊川易传 · 第 {gid:02d} 卦 · {full_name}

> **卦体**：{structure}  
> **二进制码**：`{binary}`  
> **学派属性**：北宋洛学义理派宗本（程颐著）  

---

## 📜 程氏易传原典与义理疏解

{b_text}
"""
    with open(os.path.join(target_dir, f"{gid:02d}_{full_name}.md"), "w", encoding="utf-8") as out:
        out.write(doc)
        
    # 微文档注入
    first_p = b_text.split('\n\n')[0]
    clean_p = re.sub(r'[【】-]', '', first_p)
    clean_p = re.sub(r'\s+', ' ', clean_p).strip()
    if len(clean_p) > 200:
        clean_p = clean_p[:200] + "……"
        
    yichuan_summary_block = f"""
### 2. 程颐《伊川易传》（北宋理学义理正宗）
- **序卦传逻辑与性德**：{clean_p}
- **治身体用之旨**：程子以理释易，主张“体用一源，显微无间”。居此卦之时，当体察天道运行之常理，随时变易以顺中正，修身修己以御时变。
"""
