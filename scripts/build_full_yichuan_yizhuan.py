    if os.path.exists(target_archive):
        with open(target_archive, "r", encoding="utf-8") as af:
            a_content = af.read()
        
        if "程颐《伊川易传》" not in a_content and "## 叁· 先贤义理与哲理阐微" in a_content:
            p_four = a_content.find("## 肆·")
