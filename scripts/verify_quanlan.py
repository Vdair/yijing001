results = []
found_count = 0
for num, s_name, t_name in gua_names:
    # 查找如 ䷀乾 ䷁坤 或者 乾下乾上 或者 乾：元亨
    # 在四库本全览中，看看卦名出现形式
    p1 = rf'({t_name}[：:][^\n]+)'
    p2 = rf'([䷀-䷿]?\s*{t_name}\s*[（\(][^）\)]+[）\)])'
    p3 = rf'(\n{t_name}\n)'
    p4 = rf'({s_name}[：:][^\n]+)'
    
    pos = -1
    sample = ""
    for p in [p1, p2, p3, p4]:
        m = list(re.finditer(p, text))
        if m:
            pos = m[0].start()
            sample = m[0].group(1)[:20]
            break
    
    if pos != -1:
        found_count += 1
        results.append(f"{num} {s_name}({t_name}): FOUND at {pos} -> {sample!r}")
    else:
        results.append(f"{num} {s_name}({t_name}): NOT FOUND")

with open("data/quanlan_matches.txt", "w", encoding="utf-8") as out:
    out.write(f"Total matched: {found_count} / 64\n\n" + "\n".join(results))

