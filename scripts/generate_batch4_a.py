def main():
    os.makedirs("./data", exist_ok=True)
    
    tasks = [
        ("27_山雷颐", get_yi_data),
        ("28_泽风大过", get_daguo_data),
        ("29_坎为水", get_kan_data),
        ("30_离为火", get_li_data),
    ]
    
    js_path = "./course_data.js"
    with open(js_path, "r", encoding="utf-8") as f:
        text = f.read().strip()
    
    prefix = "window.COURSE = "
    if not text.startswith(prefix):
        raise Exception("course_data.js does not start with window.COURSE = ")
    
    json_str = text[len(prefix):].rstrip(";")
    course_data = json.loads(json_str)
    
    lesson_map = {}
    for part in course_data.get("parts", []):
        for topic in part.get("topics", []):
            for i, l in enumerate(topic.get("lessons", [])):
                lesson_map[l["id"]] = (topic["lessons"], i)
                
    for tag_name, getter_fn in tasks:
        data = getter_fn()
        lesson_id = data["id"]
        md_text = data["md"]
        rich_html = data["rich_html"]
        
        md_filename = f"./data/{tag_name.split('_')[0]}_{tag_name.split('_')[1][2:] if len(tag_name.split('_')[1])>2 else tag_name.split('_')[1]}卦全息知识精研汇编.md"
        with open(md_filename, "w", encoding="utf-8") as f:
            f.write(md_text)
        print(f"✅ Written Markdown: {md_filename} ({len(md_text.encode('utf-8'))} bytes)")
        
        if lesson_id in lesson_map:
            arr, idx = lesson_map[lesson_id]
            new_item = {
                "id": lesson_id,
                "title": data["title"],
                "navTitle": data["navTitle"],
                "tag": data["tag"],
                "symbol": data["symbol"],
                "upper": data["upper"],
                "lower": data["lower"],
                "lines": data["lines"],
                "motto": data["motto"],
                "full_rich_html": rich_html
            }
            arr[idx] = new_item
            print(f"✅ Injected: {lesson_id} (HTML length: {len(rich_html)})")
        else:
            print(f"❌ Warning: {lesson_id} not found in course_data.js lessons!")
            
    new_json_str = json.dumps(course_data, ensure_ascii=False, indent=2)
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("window.COURSE = " + new_json_str + ";\n")
    print(f"🎉 Batch 4-A (27~30) Successfully committed to {js_path}! 上经三十卦全满贯达成！")

if __name__ == "__main__":
    main()
