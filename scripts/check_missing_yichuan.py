# 查看哪 3 卦 missing
missing = []
for gid, name, struct in GUA_64_STRUCTURE:
    # 查找如 name + 序卦 或 struct
    # 比如 "家人序卦" 或 "益序卦"
    p1 = rf'({name}序卦)'
    p2 = rf'({name}卦)'
    p3 = rf'({name}，)'
    p4 = rf'({name}：)'
    found = False
    for p in [p1, p2, p3, p4]:
        m = list(re.finditer(p, text))
        if m:
            found = True
            break
    if not found:
        missing.append((gid, name, struct))

print(f"Missing count: {len(missing)}")
